// Decimal (Base 10)
let decimal= 100; // Literals
console.log("Decimal: ", decimal); // Decimal: 100
 // Binary (Base 2) - start  with 0b or 0B
let binary= 0b1010; // Literals
console.log("Binary 0b1010: ", binary); // Binary: 10
// Octal (Base 8) - start with 0o or 0O
let octal= 0o77; // Literals
console.log("Octal 0o77: ", octal); // Octal: 63
// Hexadecimal (Base 16) - start with 0x or 0X
let hexadecimal= 0x2F; // Literals
console.log("Hexadecimal 0x2F: ", hexadecimal); // Hexadecimal: 47

// FLOATING POINT NUMBERS
let floatNum= 3.14; // Literals
console.log("Floating Point Number: ", floatNum); // Floating Point Number: 3.14
let floatNum2= 1.5e-4; // Literals
console.log("Floating Point Number 1.5e-4: ", floatNum2); // Floating Point Number 1.5e-4: 0.00015
let floatNum3= .5; // Literals
console.log("Floating Point Number .5: ", floatNum3); // Floating Point Number .5: 0.5
let floatNum4= 5.; // Literals
console.log("Floating Point Number 5.: ", floatNum4); // Floating Point Number 5.: 5

// Exponential Notation
let expNum= 1.5e6; // Literals
console.log("Exponential Notation 1.5e6: ", expNum); // Exponential Notation 1.5e6: 1500000
let expNum1= 1.5e-6; // Literals
console.log("Exponential Notation 1.5e-6: ", expNum1); // Exponential Notation 1.5e-6: 0.0000015
let expNum2= 5E10; // Literals
console.log("Exponential Notation 5E10: ", expNum2); 
 




